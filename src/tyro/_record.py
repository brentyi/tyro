"""Lightweight stand-in for `dataclasses.dataclass`.

Each `@dataclass` decorator generates and compiles code at import time. This typically
costs around a millisecond per class, which adds up to a significant portion of tyro's
total runtime. Internal classes inherit from `Record` and implement their `__init__()`
methods manually instead: this is stored as bytecode and is basically free.

Classes in our public API are still dataclasses.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Callable, ClassVar, Generic, TypeVar

_RecordT = TypeVar("_RecordT", bound="Record")
_OutT = TypeVar("_OutT")


class lazy_property(Generic[_OutT]):
    """Attribute that's computed the first time it's accessed.

    This is the same idea as `functools.cached_property`, which acquires a lock in older
    versions of Python."""

    def __init__(self, func: Callable[[Any], _OutT]) -> None:
        self._func = func
        self._name = func.__name__
        self.__doc__ = func.__doc__

    def __get__(self, instance: Any, owner: Any = None) -> _OutT:
        # Once this is set: lookups will skip this descriptor entirely.
        out = self._func(instance)
        instance.__dict__[self._name] = out
        return out


class Record:
    """Base class for records. Equality is identity-based by default."""

    _record_fields: ClassVar[tuple[str, ...]] = ()

    def __repr__(self) -> str:
        fields = ", ".join(f"{k}={getattr(self, k)!r}" for k in self._record_fields)
        return f"{type(self).__qualname__}({fields})"

    def replace(self: _RecordT, **changes: Any) -> _RecordT:
        """Make a shallow copy with some attributes changed."""
        out = object.__new__(type(self))
        out.__dict__.update(
            {k: v for k, v in self.__dict__.items() if k in self._record_fields}
        )
        out.__dict__.update(changes)
        return out


class ValueRecord(Record):
    """Record with value-based equality and hashing, like a frozen dataclass."""

    def _astuple(self) -> tuple[Any, ...]:
        return tuple(getattr(self, k) for k in self._record_fields)

    def __eq__(self, other: object) -> bool:
        if other.__class__ is not self.__class__:
            return NotImplemented
        return self._astuple() == other._astuple()  # type: ignore

    def __hash__(self) -> int:
        return hash(self._astuple())


class FrozenDataclassMixin(ValueRecord):
    """Implements the methods that would normally be generated by
    `@dataclasses.dataclass(frozen=True)`, without any code generation.

    This is used for classes that are dataclasses in our public API. Subclasses should
    be decorated with `@frozen_dataclass`, and initialized by writing directly to
    `__dict__`."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        # This is slow and can be overridden.
        cls = type(self)
        for name, value in zip(cls._record_fields, args):
            if name in kwargs:
                raise TypeError(f"{cls.__name__}() got multiple values for {name!r}")
            kwargs[name] = value
        if len(args) > len(cls._record_fields) or kwargs.keys() != set(
            cls._record_fields
        ):
            raise TypeError(f"{cls.__name__}() expects arguments {cls._record_fields}")
        self.__dict__.update(kwargs)

    def replace(self: _RecordT, **changes: Any) -> _RecordT:
        raise NotImplementedError("Use `dataclasses.replace()` instead.")

    def __setattr__(self, name: str, value: Any) -> None:
        import dataclasses

        raise dataclasses.FrozenInstanceError(f"cannot assign to field {name!r}")

    def __delattr__(self, name: str) -> None:
        import dataclasses

        raise dataclasses.FrozenInstanceError(f"cannot delete field {name!r}")


if TYPE_CHECKING:
    from typing_extensions import dataclass_transform

    _T = TypeVar("_T")

    @dataclass_transform(frozen_default=True)
    def frozen_dataclass(cls: type[_T]) -> type[_T]: ...

else:

    def frozen_dataclass(cls):
        """Same as `@dataclasses.dataclass(frozen=True)`, but much cheaper at import time.
        Should be applied to subclasses of `FrozenDataclassMixin`."""
        import dataclasses

        # Dataclasses that aren't frozen can't inherit from ones that are.
        frozen_bases = [b for b in cls.__mro__[1:] if "__dataclass_params__" in vars(b)]
        for base in frozen_bases:
            base.__dataclass_params__.frozen = False
        cls = dataclasses.dataclass(init=False, repr=False, eq=False)(cls)
        for base in (cls, *frozen_bases):
            base.__dataclass_params__.frozen = True
        cls._record_fields = tuple(cls.__dataclass_fields__)
        return cls
